#!/usr/bin/env python
"""Generate the regional tables and a flat CSV from regional_*.json, so no number is retyped."""
from __future__ import annotations

import csv
import json
import os
import sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OBS = os.path.join(ROOT, "artifacts", "method_vs_data", "observed_hidden")
NICE = {"k360": "ours (KITTI-360)", "waymo": "ours (Waymo)", "once": "ours (ONCE, exploratory)",
        "map_only": "map only", "occany_1f": "OccAny 1f causal",
        "occany_5f_fwd": "OccAny 5f forward [non-causal]"}
BENCH = {"semantickitti": "SemanticKITTI 08", "occ3d": "Occ3D-nuScenes val"}


def fmt(c):
    star = " \\*" if c["significant_at_95"] else " ns"
    return f"{c['delta']:+.2f} [{c['ci_low']:+.2f}, {c['ci_high']:+.2f}]{star}"


def main() -> int:
    out, rows = ["# Regional tables (generated)\n",
                 "Generated by `tools/method_vs_data/observed_hidden_tables.py`.\n"], []
    for ds in ("semantickitti", "occ3d"):
        p = os.path.join(OBS, f"regional_{ds}.json")
        if not os.path.exists(p):
            out.append(f"\n## {BENCH[ds]} — not available\n")
            continue
        d = json.load(open(p))
        arms, regions = d["arms"], d["regions"]
        out.append(f"\n# {BENCH[ds]} — {d['n_samples']} anchors\n")
        out.append("\n## Region composition\n")
        out.append("| region | valid voxels | % of valid | GT-occupied voxels | % of GT occupied |")
        out.append("|---|---:|---:|---:|---:|")
        for r in regions:
            c = d["composition"][r]
            out.append(f"| `{r}` | {c['valid_voxels']:,} | {c['share_of_valid']*100:.2f} % | "
                       f"{c['gt_occupied']:,} | {c['share_of_gt_occupied']*100:.2f} % |")
        out.append("\n## GT-occupied surface each permitted frame sees (frame_4 = anchor)\n")
        out.append("| frame | GT-occupied voxels seen | % of GT occupied |")
        out.append("|---|---:|---:|")
        for k, v in d["per_frame_observed_gt_occupied"].items():
            out.append(f"| {k} | {v['gt_occupied_seen']:,} | "
                       f"{v['share_of_gt_occupied']*100:.2f} % |")
        for post in ("raw", "pooled"):
            out.append(f"\n## SC IoU / precision / recall — {post}\n")
            out.append("| region | metric | " + " | ".join(NICE.get(a, a) for a in arms) + " |")
            out.append("|---|---|" + "---:|" * len(arms))
            for r in regions:
                for m in ("iou", "precision", "recall"):
                    out.append(f"| `{r}` | {m} | " + " | ".join(
                        f"{d['iou'][post][r][a][m]:.2f}" for a in arms) + " |")
            out.append(f"\n## Confusion counts — {post}\n")
            out.append("| region | count | " + " | ".join(NICE.get(a, a) for a in arms) + " |")
            out.append("|---|---|" + "---:|" * len(arms))
            for r in regions:
                for m in ("tp", "fp", "fn"):
                    out.append(f"| `{r}` | {m.upper()} | " + " | ".join(
                        f"{d['iou'][post][r][a][m]:,}" for a in arms) + " |")
            out.append(f"\n## Paired differences, 95 % block bootstrap — {post}\n")
            names = list(d["contrasts"][post])
            out.append("| contrast | " + " | ".join(f"`{r}`" for r in regions) + " |")
            out.append("|---|" + "---:|" * len(regions))
            for n in names:
                out.append(f"| {n} | " + " | ".join(
                    fmt(d["contrasts"][post][n][r]) for r in regions) + " |")
            for r in regions:
                for a in arms:
                    v = d["iou"][post][r][a]
                    rows.append({"dataset": ds, "postprocess": post, "region": r, "arm": a,
                                 "n_samples": d["n_samples"], **{k: v[k] for k in
                                 ("iou", "precision", "recall", "tp", "fp", "fn")},
                                 "valid_voxels": d["composition"][r]["valid_voxels"],
                                 "gt_occupied": d["composition"][r]["gt_occupied"]})
        out.append("\n## Partition check\n")
        tot = {m: sum(d["iou"]["raw"][r]["k360"][m] for r in d["partition"])
               for m in ("tp", "fp", "fn")}
        glob = {m: d["iou"]["raw"]["all"]["k360"][m] for m in ("tp", "fp", "fn")}
        out.append("| quantity | sum over the four partition regions | global `all` | equal |")
        out.append("|---|---:|---:|---|")
        for m in ("tp", "fp", "fn"):
            out.append(f"| {m.upper()} (ours KITTI-360, raw) | {tot[m]:,} | {glob[m]:,} | "
                       f"{'yes' if tot[m] == glob[m] else 'NO'} |")
        sv = sum(d["composition"][r]["valid_voxels"] for r in d["partition"])
        out.append(f"| valid voxels | {sv:,} | {d['composition']['all']['valid_voxels']:,} | "
                   f"{'yes' if sv == d['composition']['all']['valid_voxels'] else 'NO'} |")

    os.makedirs(OBS, exist_ok=True)
    open(os.path.join(OBS, "tables.md"), "w").write("\n".join(out) + "\n")
    if rows:
        with open(os.path.join(OBS, "metrics.csv"), "w", newline="") as fh:
            w = csv.DictWriter(fh, fieldnames=list(rows[0]))
            w.writeheader()
            w.writerows(rows)
    print(f"-> {os.path.join(OBS, 'tables.md')}  ({len(rows)} csv rows)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
