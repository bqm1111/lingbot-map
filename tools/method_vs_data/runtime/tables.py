#!/usr/bin/env python
"""Generate the runtime tables from the measurement JSONs, so no number is retyped."""
from __future__ import annotations

import json
import os
import sys

R = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..",
                                 "artifacts", "method_vs_data", "runtime"))
GiB = 2 ** 30


def L(n):
    p = os.path.join(R, n)
    return json.load(open(p)) if os.path.exists(p) else None


CONF = [("Ours — 5 causal frames", "SemanticKITTI", "ours_semantickitti_5f_e2e.json", 5, 0, "causal"),
        ("Ours — 1 causal frame", "SemanticKITTI", "ours_semantickitti_1f_e2e.json", 1, 0, "causal"),
        ("Ours — 5 causal frames", "Occ3D", "ours_occ3d_5f_e2e.json", 5, 0, "causal"),
        ("OccAny — 1 causal frame", "SemanticKITTI", "occany_K_1FRAME_GEOM_e2e.json", 1, 150, "causal"),
        ("OccAny — 5 forward frames", "SemanticKITTI", "occany_K_5FRAMES_GEOM_e2e.json", 5, 150, "forward t..t+40")]


def main() -> int:
    out = ["# Runtime measurement tables (generated)\n",
           "Generated by `tools/method_vs_data/runtime/tables.py` from the JSONs beside it.\n"]
    out.append("\n## Latency and memory, per completed occupancy grid\n")
    out.append("| configuration | benchmark | real input frames | generated views | window | "
               "mean (ms) | median (ms) | p95 (ms) | predictions/s | peak allocated (GiB) | "
               "peak reserved (GiB) |")
    out.append("|---|---|---:|---:|---|---:|---:|---:|---:|---:|---:|")
    for name, bench, f, nf, gv, win in CONF:
        d = L(f)
        if not d:
            continue
        s = d["latency_per_completed_occupancy_grid"]
        m = d["peak_memory"]
        out.append(f"| {name} | {bench} | {nf} | {gv} | {win} | {s['mean_ms']:.1f} | "
                   f"{s['median_ms']:.1f} | {s['p95_ms']:.1f} | "
                   f"{s['predictions_per_second']:.2f} | {m['allocated_bytes']/GiB:.2f} | "
                   f"{m['reserved_bytes']/GiB:.2f} |")

    out.append("\n## Stage breakdown — ours (measured in `--mode stages`)\n")
    out.append("| stage | SemanticKITTI 5f (ms) | share | Occ3D 5f (ms) |")
    out.append("|---|---:|---:|---:|")
    a, b = L("ours_semantickitti_5f_stages.json"), L("ours_occ3d_5f_stages.json")
    tot = sum(a["stages_mean_ms"].values())
    for k in a["stages_mean_ms"]:
        out.append(f"| {k} | {a['stages_mean_ms'][k]:.2f} | {100*a['stages_mean_ms'][k]/tot:.1f} % "
                   f"| {b['stages_mean_ms'][k]:.2f} |" if b else
                   f"| {k} | {a['stages_mean_ms'][k]:.2f} | {100*a['stages_mean_ms'][k]/tot:.1f} % | — |")
    out.append(f"| **sum of stages** | **{tot:.2f}** | 100 % | "
               f"**{sum(b['stages_mean_ms'].values()):.2f}** |" if b else
               f"| **sum of stages** | **{tot:.2f}** | 100 % | — |")
    out.append(f"| *(image decode, COLD cache, measured once per anchor before warm-up; the timed preprocess stage already contains a warm-cache decode, so this is NOT subtractable)* | "
               f"*{a['image_decode_excluded_by_boundary']['mean_ms']:.2f}* | — | "
               f"*{b['image_decode_excluded_by_boundary']['mean_ms']:.2f}* |")

    out.append("\n## Stage breakdown — OccAny (measured in `--mode stages`)\n")
    out.append("| segment | 5 forward frames (ms) | 1 causal frame (ms) |")
    out.append("|---|---:|---:|")
    c, d_ = L("occany_K_5FRAMES_GEOM_stages.json"), L("occany_K_1FRAME_GEOM_stages.json")
    for k in ("network_mean_ms", "assemble_outputs_mean_ms", "dict_tail_and_recon_mask_mean_ms",
              "voxelise_recon_only_NOT_REQUIRED_mean_ms", "voxelise_combined_mean_ms",
              "post_network_segment_mean_ms", "e2e_less_recon_only_voxelisation_mean_ms"):
        out.append(f"| {k.replace('_mean_ms','')} | {c['stages_mean_ms'].get(k, float('nan')):.2f} "
                   f"| {d_['stages_mean_ms'].get(k, float('nan')):.2f} |")

    out.append("\n## Parameters\n")
    out.append("| module | total parameters | trainable at inference | optimised by this work |")
    out.append("|---|---:|---:|---|")
    p = L("ours_semantickitti_5f_e2e.json")["parameters"]
    tot_ours = 0
    for k, v in p["per_module_total_and_requires_grad"].items():
        tot_ours += v[0]
        own = "yes" if k == "completion_unet" else "no — frozen pretrained dependency"
        out.append(f"| ours: {k} | {v[0]:,} | {v[1]:,} | {own} |")
    out.append(f"| **ours: total inference parameters** | **{tot_ours:,}** | 0 | "
               f"{p['task_specific_trained_parameters']:,} |")
    oc = L("occany_K_5FRAMES_GEOM_e2e.json")["parameters"][
        "counted_by_their_own_count_unique_parameters"]
    out.append(f"| OccAny: encoder + decoder + raymap_encoder + gen_decoder | {oc['total']:,} "
               f"| {oc['requires_grad']:,} | released checkpoint, fully trained |")

    out.append("\n## Ratios (mean latency)\n")
    u5 = L("ours_semantickitti_5f_e2e.json")["latency_per_completed_occupancy_grid"]["mean_ms"]
    u1 = L("ours_semantickitti_1f_e2e.json")["latency_per_completed_occupancy_grid"]["mean_ms"]
    o5 = L("occany_K_5FRAMES_GEOM_e2e.json")["latency_per_completed_occupancy_grid"]["mean_ms"]
    o1 = L("occany_K_1FRAME_GEOM_e2e.json")["latency_per_completed_occupancy_grid"]["mean_ms"]
    adj = c["stages_mean_ms"]["e2e_less_recon_only_voxelisation_mean_ms"]
    out.append("| comparison | ratio |")
    out.append("|---|---:|")
    out.append(f"| OccAny 5 forward / ours 5 causal | {o5/u5:.2f} x |")
    out.append(f"| OccAny 5 forward / ours 5 causal, after removing OccAny's unnecessary "
               f"reconstruction-only voxelisation | {adj/u5:.2f} x |")
    out.append(f"| OccAny 1 causal / ours 1 causal | {o1/u1:.2f} x |")
    out.append(f"| OccAny 1 causal / ours 5 causal | {o1/u5:.2f} x |")
    out.append(f"| ours inference parameters / OccAny | {tot_ours/oc['total']:.2f} x |")

    out.append("\n## Cross-arm consistency: does the trained source change the cost?\n")
    ua = L("unet_arm_consistency.json")
    if ua:
        out.append("| arm | CompletionUNet parameters | mean (ms) | median (ms) |")
        out.append("|---|---:|---:|---:|")
        for k, v in ua["arms"].items():
            out.append(f"| {k} | {v.get('n_params', 0):,} | {v.get('mean_ms', float('nan')):.3f} "
                       f"| {v.get('median_ms', float('nan')):.3f} |")

    out.append("\n## Verification against the cached canonical predictions\n")
    vz = L("verify_ours_semantickitti_5f.json")
    if vz:
        out.append(f"- anchors checked: {vz['n_checked']}")
        out.append(f"- bit-identical: {vz['all_identical']}")
        out.append(f"- mean voxel agreement (IoU of the two occupancy sets): "
                   f"{vz['mean_agreement_iou']:.3f} %, minimum {vz['min_agreement_iou']:.3f} %")
        out.append(f"- mean fraction of voxels that disagree: "
                   f"{vz['mean_disagreeing_voxel_fraction']*100:.4f} %")
        out.append(f"- mean SC IoU difference (timed minus cached): "
                   f"{vz['sc_iou_difference_mean']:+.4f}; largest absolute difference on any "
                   f"anchor {vz['sc_iou_difference_max_abs']:.4f}")

    out.append("\n## Machine\n")
    m = L("ours_semantickitti_5f_e2e.json")["machine"]
    for k in ("gpu_name", "gpu_capability", "driver", "cpu_model", "cpu_count", "platform",
              "python", "torch", "torch_cuda", "cudnn", "loadavg", "nvidia_smi_during_setup"):
        v = m.get(k)
        if k == "driver" and isinstance(v, str):
            v = sorted(set(v.split()))[0]
        if k == "nvidia_smi_during_setup" and isinstance(v, str):
            v = " ; ".join(x.strip() for x in v.splitlines())
        out.append(f"- **{k}**: {v}")
    mo = L("occany_K_5FRAMES_GEOM_e2e.json")["machine"]
    out.append(f"- **OccAny interpreter**: {mo['executable']}, python {mo['python']}, "
               f"torch {mo['torch']} (cuda {mo['torch_cuda']}, cudnn {mo['cudnn']})")
    out.append(f"- **OccAny CUDA_VISIBLE_DEVICES**: {mo['cuda_visible_devices']} "
               f"(the same physical GPU as ours)")

    path = os.path.join(R, "tables.md")
    open(path, "w").write("\n".join(out) + "\n")
    print("\n".join(out))
    print("\n->", path)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
