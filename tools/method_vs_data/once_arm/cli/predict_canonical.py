#!/usr/bin/env python
"""Canonical-protocol predictions with the ONCE geometry checkpoint and NOTHING else changed.

This is the only protocol on which our arms can be compared with OccAny: 801 SemanticKITTI and
4,219 Occ3D anchors, OccAny's own labels, placement and scorer. It runs the frozen prediction
pipeline verbatim and substitutes one object -- the ``CompletionUNet`` that
``semantic_completion.frozen_geometry.load_frozen_geometry`` returns. Everything else is
untouched: the clips, tokens, anchors, grids, evidence lift and readout.

Two substitutions, both confined to this file, exactly as the Waymo arm's Phase 4 did:

* ``pipeline.load_frozen_geometry`` is bound to this arm's checkpoint directory and to a
  freeze record generated here from those checkpoints' real hashes, so the frozen loader's own
  sha256 assertion still runs and still has something true to check;
* ``zero_shot_eval.config.PREDICTION_ROOT`` is redirected so the frozen KITTI-360 prediction
  cache is never written to, with an assertion that refuses to start if the redirect failed.

``GEOMETRY_SEED`` stays 0, so the ONCE seed-0 checkpoint replaces the KITTI-360 seed-0
checkpoint one for one.

    CUDA_VISIBLE_DEVICES=3 PYTHONPATH=$PWD python \\
        tools/method_vs_data/once_arm/cli/predict_canonical.py --dataset semantickitti \\
        --device cuda:0
"""
from __future__ import annotations

import argparse
import dataclasses
import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..", "..")))
from tools.method_vs_data.once_arm import config as A                                   # noqa: E402
from tools.semantic_completion import config as SCC                                     # noqa: E402
from tools.semantic_completion import frozen_geometry as FG                             # noqa: E402
from tools.zero_shot_eval import config as ZC                                           # noqa: E402
from tools.zero_shot_eval.prediction import pipeline as PL                              # noqa: E402

PREDICTION_ROOT = os.path.join(A.DATA_ROOT, "zero_shot_predictions")
FREEZE_PATH = os.path.join(A.ARTIFACT_DIR, "geometry_freeze.json")


def write_geometry_freeze() -> str:
    """A freeze record for THIS arm's checkpoints, in the format the frozen loader expects."""
    ck_dir = A.Paths().checkpoints
    rec = {"note": ("generated by tools/method_vs_data/once_arm/cli/predict_canonical.py so "
                    "the frozen geometry loader has a true record to assert against for THIS "
                    "arm's checkpoints; it does not replace artifacts/baseline_reconstruction/"
                    "code_freeze.json, which still governs the KITTI-360 arm"),
           "arm": A.VERSION, "status": A.STATUS, "sha256": {}}
    for s in A.SEEDS:
        p = os.path.join(ck_dir, f"geo_seed{s}_step06000.pt")
        rec["sha256"][os.path.relpath(p, A.REPO_ROOT)] = \
            hashlib.sha256(open(p, "rb").read()).hexdigest()
    os.makedirs(os.path.dirname(FREEZE_PATH), exist_ok=True)
    json.dump(rec, open(FREEZE_PATH, "w"), indent=1)
    return FREEZE_PATH


def install_once_geometry() -> dict:
    write_geometry_freeze()
    once_paths = dataclasses.replace(SCC.Paths(),
                                     geometry_checkpoints=A.Paths().checkpoints,
                                     geometry_freeze=FREEZE_PATH)
    real = FG.load_frozen_geometry

    def _load(seed, device, paths=None):
        return real(seed, device, once_paths)

    PL.load_frozen_geometry = _load
    ZC.PREDICTION_ROOT = PREDICTION_ROOT          # prediction_path reads this at call time
    os.makedirs(PREDICTION_ROOT, exist_ok=True)
    return {"checkpoints": once_paths.geometry_checkpoints, "freeze": FREEZE_PATH,
            "prediction_root": PREDICTION_ROOT, "geometry_seed": ZC.GEOMETRY_SEED}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dataset", required=True, choices=["semantickitti", "occ3d"])
    ap.add_argument("--device", default="cuda:0")
    ap.add_argument("--shard", type=int, default=0)
    ap.add_argument("--shards", type=int, default=1)
    ap.add_argument("--limit", type=int, default=None)
    a = ap.parse_args()
    A.ensure_dirs()
    info = install_once_geometry()
    print(f"[canonical] geometry <- {info['checkpoints']} (seed {info['geometry_seed']})",
          flush=True)
    print(f"[canonical] predictions -> {info['prediction_root']}", flush=True)
    assert ZC.prediction_path(a.dataset, "X").startswith(PREDICTION_ROOT), \
        "prediction redirect failed; refusing to write into the frozen cache"
    rec = PL.run_shard(a.dataset, a.device, a.shard, a.shards, a.limit)
    rec.update(info)
    rec["provenance"] = A.provenance()
    d = A.Paths().logs
    os.makedirs(d, exist_ok=True)
    path = os.path.join(d, f"predict_canonical_{a.dataset}_s{a.shard}of{a.shards}.json")
    json.dump(rec, open(path, "w"), indent=1, default=float)
    print(f"[canonical] -> {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
