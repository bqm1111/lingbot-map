#!/usr/bin/env python
"""Phase 4 — canonical predictions with the Waymo geometry checkpoint and NOTHING else changed.

The brief's requirement is to isolate the effect of better (or worse) predicted geometry on
semantic occupancy. So this runs the frozen prediction pipeline verbatim and substitutes one
object: the `CompletionUNet` that `semantic_completion.frozen_geometry.load_frozen_geometry`
returns. Trident-H, the evidence lift, the B0 nearest-evidence rule, the B3 heads, the text
readout, the vocabulary, the clips, the tokens, the anchors and the grids are untouched.

Two substitutions, both confined to this file:

* ``pipeline.load_frozen_geometry`` is bound to the Waymo arm's checkpoint directory and to
  a freeze record generated here from those checkpoints' real hashes. The frozen loader's
  own sha256 assertion therefore still runs and still has something true to check.
* ``zero_shot_eval.config.PREDICTION_ROOT`` is redirected so the frozen KITTI-360 prediction
  cache is never written to. ``prediction_path`` reads that global at call time.

``GEOMETRY_SEED`` stays 0, matching the frozen pipeline, so the Waymo seed-0 checkpoint
replaces the KITTI-360 seed-0 checkpoint one for one.

    CUDA_VISIBLE_DEVICES=2 PYTHONPATH=$PWD python tools/waymo_arm/cli/predict_semantic.py \\
        --dataset semantickitti --device cuda:0 --shard 0 --shards 1
"""
from __future__ import annotations

import argparse
import dataclasses
import hashlib
import json
import os
import sys

sys.path.insert(0, os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", "..")))
from tools.semantic_completion import config as SCC                                     # noqa: E402
from tools.semantic_completion import frozen_geometry as FG                             # noqa: E402
from tools.waymo_arm import config as A                                                 # noqa: E402
from tools.zero_shot_eval import config as ZC                                           # noqa: E402
from tools.zero_shot_eval.prediction import pipeline as PL                              # noqa: E402

#: where this arm's canonical predictions go; the frozen cache is never touched
PREDICTION_ROOT = os.path.join(A.DATA_ROOT, "zero_shot_predictions")
FREEZE_PATH = os.path.join(A.ARTIFACT_DIR, "geometry_freeze.json")


def write_geometry_freeze() -> str:
    """A freeze record for the Waymo checkpoints, in the format the frozen loader expects."""
    ck_dir = A.Paths().checkpoints
    rec = {"note": ("generated by tools/waymo_arm/cli/predict_semantic.py so the frozen "
                    "geometry loader has a true record to assert against for THIS arm's "
                    "checkpoints; it does not replace artifacts/baseline_reconstruction/"
                    "code_freeze.json, which still governs the KITTI-360 arm"),
           "sha256": {}}
    for s in A.SEEDS:
        p = os.path.join(ck_dir, f"geo_seed{s}_step06000.pt")
        rec["sha256"][os.path.relpath(p, A.REPO_ROOT)] = \
            hashlib.sha256(open(p, "rb").read()).hexdigest()
    os.makedirs(os.path.dirname(FREEZE_PATH), exist_ok=True)
    json.dump(rec, open(FREEZE_PATH, "w"), indent=1)
    return FREEZE_PATH


def install_waymo_geometry() -> dict:
    write_geometry_freeze()
    waymo_paths = dataclasses.replace(SCC.Paths(),
                                      geometry_checkpoints=A.Paths().checkpoints,
                                      geometry_freeze=FREEZE_PATH)
    real = FG.load_frozen_geometry

    def _load(seed, device, paths=None):
        return real(seed, device, waymo_paths)

    PL.load_frozen_geometry = _load
    ZC.PREDICTION_ROOT = PREDICTION_ROOT          # prediction_path reads this at call time
    os.makedirs(PREDICTION_ROOT, exist_ok=True)
    return {"checkpoints": waymo_paths.geometry_checkpoints,
            "freeze": FREEZE_PATH, "prediction_root": PREDICTION_ROOT,
            "geometry_seed": ZC.GEOMETRY_SEED}


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dataset", required=True, choices=["semantickitti", "occ3d"])
    ap.add_argument("--device", default="cuda:0")
    ap.add_argument("--shard", type=int, default=0)
    ap.add_argument("--shards", type=int, default=1)
    ap.add_argument("--limit", type=int, default=None)
    a = ap.parse_args()
    A.ensure_dirs()
    info = install_waymo_geometry()
    print(f"[phase4] geometry <- {info['checkpoints']} (seed {info['geometry_seed']})", flush=True)
    print(f"[phase4] predictions -> {info['prediction_root']}", flush=True)
    assert ZC.prediction_path(a.dataset, "X").startswith(PREDICTION_ROOT), \
        "prediction redirect failed; refusing to write into the frozen cache"
    rec = PL.run_shard(a.dataset, a.device, a.shard, a.shards, a.limit)
    rec.update(info)
    d = os.path.join(A.Paths().logs)
    os.makedirs(d, exist_ok=True)
    path = os.path.join(d, f"predict_{a.dataset}_s{a.shard}of{a.shards}.json")
    json.dump(rec, open(path, "w"), indent=1, default=float)
    print(f"\n[phase4] {rec['written']} written of {rec['samples']}, "
          f"{rec['seconds'] / 60:.1f} min -> {path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
